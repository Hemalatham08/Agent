"""Chart spec builders derived from read-only ERP analytics tool output.

Each builder inspects one tool's result dictionary and returns a single
:class:`~backend.agent.charts.specs.ChartSpec` when the result is chartable,
or ``None`` otherwise. All values come from verified tool output; nothing is
generated by a language model.
"""

from __future__ import annotations

from typing import Any

from backend.agent.charts.specs import ChartSpec

# A chart is only emitted when there are enough rows to be meaningful and the
# result was not truncated in a way that hides significant data.
_MIN_ROWS = 2
_MAX_ROWS = 50


def _first_row(output: dict[str, Any]) -> dict[str, Any] | None:
    rows = output.get("rows")
    if isinstance(rows, list) and rows:
        return rows[0]
    return None


def _chartable_rows(output: dict[str, Any]) -> list[dict[str, Any]] | None:
    rows = output.get("rows")
    if not isinstance(rows, list):
        return None
    if len(rows) < _MIN_ROWS or len(rows) > _MAX_ROWS:
        return None
    return rows


def _has_column(rows: list[dict[str, Any]], column: str) -> bool:
    return bool(rows) and column in rows[0]


def _series(
    rows: list[dict[str, Any]], x_field: str, y_fields: list[str]
) -> list[dict[str, Any]]:
    """Project rows onto the x field and requested y fields."""
    projected: list[dict[str, Any]] = []
    for row in rows:
        point: dict[str, Any] = {"x": row.get(x_field)}
        for y_field in y_fields:
            point[y_field] = row.get(y_field)
        projected.append(point)
    return projected


def _spec(
    *,
    chart_type: str,
    title: str,
    rows: list[dict[str, Any]],
    x_field: str,
    y_fields: list[str],
    x_label: str = "",
    y_label: str = "",
) -> ChartSpec:
    return ChartSpec(
        chart_type=chart_type,
        title=title,
        data=_series(rows, x_field, y_fields),
        x_field=x_field,
        y_fields=list(y_fields),
        x_label=x_label,
        y_label=y_label,
    )


def _time_series_chart_type(group_by: str) -> str:
    return "line" if group_by in ("month", "quarter") else "bar"


def sales_summary_chart(output: dict[str, Any]) -> ChartSpec | None:
    rows = _chartable_rows(output)
    if rows is None:
        return None
    group_by = output.get("group_by")
    basis = output.get("basis")
    if not _has_column(rows, "revenue"):
        return None
    chart_type = _time_series_chart_type(group_by or "")
    title = f"Sales revenue by {group_by} ({basis})"
    return _spec(
        chart_type=chart_type,
        title=title,
        rows=rows,
        x_field="key",
        y_fields=["revenue"],
        x_label=group_by or "Group",
        y_label="Revenue",
    )


def purchase_summary_chart(output: dict[str, Any]) -> ChartSpec | None:
    rows = _chartable_rows(output)
    if rows is None:
        return None
    group_by = output.get("group_by")
    basis = output.get("basis")
    y_field = "ordered_value" if basis == "ordered" else "received_value"
    if not _has_column(rows, y_field):
        return None
    chart_type = _time_series_chart_type(group_by or "")
    title = f"Purchase {basis} value by {group_by}"
    return _spec(
        chart_type=chart_type,
        title=title,
        rows=rows,
        x_field="key",
        y_fields=[y_field],
        x_label=group_by or "Group",
        y_label="Value",
    )


def movement_summary_chart(output: dict[str, Any]) -> ChartSpec | None:
    rows = _chartable_rows(output)
    if rows is None:
        return None
    group_by = output.get("group_by")
    if not _has_column(rows, "net_change"):
        return None
    chart_type = _time_series_chart_type(group_by or "")
    title = f"Stock movement net change by {group_by}"
    return _spec(
        chart_type=chart_type,
        title=title,
        rows=rows,
        x_field="key",
        y_fields=["net_change"],
        x_label=group_by or "Group",
        y_label="Net change",
    )


def fulfillment_summary_chart(output: dict[str, Any]) -> ChartSpec | None:
    rows = _chartable_rows(output)
    if rows is None:
        return None
    group_by = output.get("group_by")
    if not _has_column(rows, "order_fill_pct"):
        return None
    title = f"Order fill rate by {group_by}"
    return _spec(
        chart_type="bar",
        title=title,
        rows=rows,
        x_field="key",
        y_fields=["order_fill_pct"],
        x_label=group_by or "Group",
        y_label="Fill rate (%)",
    )


_BUILDERS: dict[str, callable] = {
    "erp.finance.sales_summary": sales_summary_chart,
    "erp.finance.purchase_summary": purchase_summary_chart,
    "erp.warehouse.movement_summary": movement_summary_chart,
    "erp.fulfillment.summary": fulfillment_summary_chart,
}


def build_chart(tool_name: str, output: Any) -> ChartSpec | None:
    """Build one chart spec for a tool output, or ``None`` if not chartable."""
    if not isinstance(output, dict):
        return None
    builder = _BUILDERS.get(tool_name)
    if builder is None:
        return None
    try:
        return builder(output)
    except Exception:
        return None


__all__ = ["build_chart", "sales_summary_chart", "purchase_summary_chart"]
